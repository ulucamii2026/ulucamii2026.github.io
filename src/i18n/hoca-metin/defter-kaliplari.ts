export const tk = sozluk(KALIP_ETIKETLERI);

type Anahtar = keyof typeof tr;
const tersHarita = (onek: string): Record<string, Anahtar> =>
  Object.fromEntries((Object.entries(tr) as [Anahtar, string][]).filter(([k]) => k.startsWith(onek)).map(([k, v]) => [v, k]));
const ETIKET_ANAHTARI = tersHarita('e.');
const GRUP_ANAHTARI = tersHarita('g.');
const HAZIR_ANAHTARI: Record<string, { etiket: Anahtar; aciklama: Anahtar }> = {
  'islendi-iyi': { etiket: 'h.islendiiyi', aciklama: 'a.islendiiyi' },
  'islendi-tekrar': { etiket: 'h.islenditekrar', aciklama: 'a.islenditekrar' },
  kismen: { etiket: 'h.kismen', aciklama: 'a.kismen' },
  ertelendi: { etiket: 'h.ertelendi', aciklama: 'a.ertelendi' },
};

/** lib'deki Türkçe çip etiketi → arayüz dilindeki etiket (Türkçede aynen; bilinmeyen etiket aynen). */
export function kalipEtiketi(etiket: string): string {
  if (hocaDili() === 'tr') return etiket;
  const k = ETIKET_ANAHTARI[etiket];
  if (k) return tk(k);
  if (etiket.startsWith('Kaynak: ')) return tk('e.kaynak', { kaynak: etiket.slice('Kaynak: '.length) });
  return etiket;
}
/** lib'deki Türkçe grup adı → arayüz dilindeki ad. */
export function kalipGrupAdi(ad: string): string {
  if (hocaDili() === 'tr') return ad;
  const k = GRUP_ANAHTARI[ad];
  return k ? tk(k) : ad;
}
/** Hazır kayıt etiketi (kimliğe göre; bilinmeyen kimlikte lib'in Türkçe etiketi). */
export function hazirKayitEtiketi(h: { id: string; etiket: string }): string {
  if (hocaDili() === 'tr') return h.etiket;
  const k = HAZIR_ANAHTARI[h.id];
  return k ? tk(k.etiket) : h.etiket;
}
/** Hazır kayıt açıklaması; `sonrakiKonu` yalnız «Ertelendi» için (dersin ardından gelen dersin konusu, yoksa boş). */
export function hazirKayitAciklamasi(h: { id: string; aciklama: string }, sonrakiKonu?: string): string {
  if (hocaDili() === 'tr') return h.aciklama;
  const k = HAZIR_ANAHTARI[h.id];
  if (!k) return h.aciklama;
  if (h.id === 'ertelendi') return sonrakiKonu ? tk('a.ertelendi', { konu: sonrakiKonu }) : tk('a.ertelendisiz');
  return tk(k.aciklama);
}
